export type Tx = (s: string, vars?: Record<string, string | number>) => string

/** Prevod za karticu zaduživanja: BHS ostaje original, EN iz rječnika (nepoznato ostaje original). */
export function useTx(): Tx {
  const { lang } = useLang()
  return useCallback((s, vars) => {
    let out = lang === 'en' ? (EN[s] ?? s) : s
    if (vars) for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v))
    return out
  }, [lang])
}
