// COST SUMMARY — troškovnik po opremi
// =====================================================

export async function getCostSummary() {
  await requireRole(['engineer', 'admin'])

  if (isDemoMode()) {
    const [purchases, consumption, maintenance] = await Promise.all([
      db.partPurchase.findMany(),
      db.partConsumption.findMany(),
      db.maintenanceLog.findMany({ where: { cost: { not: null } } }),
    ])

    const totalPurchases = purchases.reduce((s, p) => s + p.totalGross, 0)
    const totalConsumption = consumption.reduce((s, c) => s + (c.totalCost ?? 0), 0)
    const totalMaintenance = maintenance.reduce((s, m) => s + (m.cost ?? 0), 0)

    return {
      totalPurchases, totalConsumption, totalMaintenance,
      grandTotal: totalPurchases + totalConsumption + totalMaintenance,
      purchaseCount: purchases.length,
      consumptionCount: consumption.length,
      maintenanceCount: maintenance.length,
    }
  }

  const supabase = await createSupabaseClient()
  const [purchasesRes, consumptionRes, maintenanceRes] = await Promise.all([
    supabase.from('part_purchases').select('total_gross'),
    supabase.from('part_consumption').select('total_cost'),
    supabase.from('maintenance_log').select('cost'),
  ])

  const totalPurchases = (purchasesRes.data ?? []).reduce((s: number, p: any) => s + (p.total_gross ?? 0), 0)
  const totalConsumption = (consumptionRes.data ?? []).reduce((s: number, c: any) => s + (c.total_cost ?? 0), 0)
  const totalMaintenance = (maintenanceRes.data ?? []).reduce((s: number, m: any) => s + (m.cost ?? 0), 0)

  return {
    totalPurchases, totalConsumption, totalMaintenance,
    grandTotal: totalPurchases + totalConsumption + totalMaintenance,
    purchaseCount: purchasesRes.data?.length ?? 0,
    consumptionCount: consumptionRes.data?.length ?? 0,
    maintenanceCount: maintenanceRes.data?.length ?? 0,
  }
}
