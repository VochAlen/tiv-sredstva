export async function consumePart(params: {
  partId: string; partNumber: string; partName: string
  equipmentId?: string; equipmentCode?: string
  quantity: number; unitPriceNet?: number; consumedBy?: string; notes?: string
}) {
  await requireRole(['engineer', 'admin'])

  const qty = params.quantity
  const unitPrice = params.unitPriceNet ?? 0
  const totalCost = qty * unitPrice

  if (isDemoMode()) {
    await db.partConsumption.create({ data: {
      partId: params.partId, partNumber: params.partNumber, partName: params.partName,
      equipmentId: params.equipmentId ?? null, equipmentCode: params.equipmentCode ?? null,
      quantity: qty, unitPriceNet: unitPrice, totalCost,
      consumedBy: params.consumedBy ?? null, notes: params.notes ?? null,
    }})

    // Smanji stanje u magacinu
    const part = await db.sparePart.findUnique({ where: { id: params.partId } })
    if (part) {
      await db.sparePart.update({
        where: { id: params.partId },
        data: { quantity: Math.max(0, part.quantity - qty) },
      })
    }

    revalidatePath('/dashboard')
    return { ok: true }
  }

  const supabase = await createSupabaseClient()
  await supabase.from('part_consumption').insert({
    part_id: params.partId, part_number: params.partNumber, part_name: params.partName,
    equipment_id: params.equipmentId ?? null, equipment_code: params.equipmentCode ?? null,
    quantity: qty, unit_price_net: unitPrice, total_cost: totalCost,
    consumed_by: params.consumedBy ?? null, notes: params.notes ?? null,
  })

  // Smanji stanje
  const { data: part } = await supabase.from('spare_parts').select('quantity').eq('id', params.partId).single()
  if (part) {
    await supabase.from('spare_parts').update({ quantity: Math.max(0, part.quantity - qty) }).eq('id', params.partId)
  }

  revalidatePath('/dashboard')
  return { ok: true }
}

