export async function addPartPurchase(params: {
  partId?: string; partNumber: string; partName: string
  orderNumber?: string; supplier: string; supplierAddress?: string
  invoiceNumber?: string; invoiceDate?: string
  quantity: number; unitPriceNet: number; vatRate?: number
  paymentMethod?: string; notes?: string; purchasedBy?: string
}) {
  await requireRole(['engineer', 'admin'])
  const user = await getCurrentUser()

  const qty = params.quantity
  const unitNet = params.unitPriceNet
  const vatRate = params.vatRate ?? 21
  const totalNet = qty * unitNet
  const vatAmount = totalNet * (vatRate / 100)
  const totalGross = totalNet + vatAmount

  if (isDemoMode()) {
    const purchase = await db.partPurchase.create({ data: {
      partId: params.partId ?? null, partNumber: params.partNumber, partName: params.partName,
      orderNumber: params.orderNumber ?? null, supplier: params.supplier, supplierAddress: params.supplierAddress ?? null,
      invoiceNumber: params.invoiceNumber ?? null, invoiceDate: params.invoiceDate ? new Date(params.invoiceDate) : null,
      quantity: qty, unitPriceNet: unitNet, vatRate, vatAmount, totalNet, totalGross,
      paymentMethod: params.paymentMethod ?? null, notes: params.notes ?? null,
      purchasedBy: user?.full_name ?? null,
    }})

    // Ažuriraj stanje u magacinu
    if (params.partId) {
      const part = await db.sparePart.findUnique({ where: { id: params.partId } })
      if (part) {
        await db.sparePart.update({
          where: { id: params.partId },
          data: { quantity: part.quantity + qty, unitPrice: unitNet },
        })
      }
    }

    revalidatePath('/dashboard')
    return { ok: true, id: purchase.id }
  }

  const supabase = await createSupabaseClient()
  const { data, error } = await supabase.from('part_purchases').insert({
    part_id: params.partId ?? null, part_number: params.partNumber, part_name: params.partName,
    order_number: params.orderNumber ?? null, supplier: params.supplier, supplier_address: params.supplierAddress ?? null,
    invoice_number: params.invoiceNumber ?? null, invoice_date: params.invoiceDate ?? null,
    quantity: qty, unit_price_net: unitNet, vat_rate: vatRate, vat_amount: vatAmount,
    total_net: totalNet, total_gross: totalGross,
    payment_method: params.paymentMethod ?? null, notes: params.notes ?? null,
    purchased_by: user?.full_name ?? null,
  }).select().single()

  if (error) throw error

  // Ažuriraj stanje
  if (params.partId) {
    const { data: part } = await supabase.from('spare_parts').select('quantity').eq('id', params.partId).single()
    if (part) {
      await supabase.from('spare_parts').update({ quantity: part.quantity + qty, unit_price: unitNet }).eq('id', params.partId)
    }
  }

  revalidatePath('/dashboard')
  return { ok: true, id: data?.id }
}

