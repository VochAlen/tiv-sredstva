// MAINTENANCE SCHEDULING — auto-generation + alerts
// =====================================================

export async function autoGenerateSchedules() {
  await requireRole(['engineer', 'admin'])

  if (isDemoMode()) {
    const equipment = await db.equipment.findMany()
    let generated = 0

    for (const eq of equipment) {
      // 1. Hours-based (svakih maintenanceIntervalHours)
      const nextHourService = eq.lastMaintenanceHours + eq.maintenanceIntervalHours
      const existingHour = await db.maintenanceSchedule.findFirst({
        where: { equipmentId: eq.id, maintenanceType: 'PREVENTIVE', status: { in: ['SCHEDULED', 'DUE'] } },
      })
      if (!existingHour) {
        await db.maintenanceSchedule.create({
          data: {
            equipmentId: eq.id, equipmentCode: eq.code, equipmentName: eq.name,
            maintenanceType: 'PREVENTIVE',
            title: `Servis na ${eq.maintenanceIntervalHours}h`,
            description: 'Preventivno održavanje po radnim satima',
            triggerHours: nextHourService,
            triggerInterval: eq.maintenanceIntervalHours,
            status: eq.totalOperatingHours >= nextHourService ? 'DUE' : 'SCHEDULED',
            priority: 'MEDIUM', autoGenerated: true,
          },
        })
        generated++
      }

      // 2. KM-based (svakih maintenanceIntervalKm)
      const nextKmService = eq.lastMaintenanceKm + eq.maintenanceIntervalKm
      const existingKm = await db.maintenanceSchedule.findFirst({
        where: { equipmentId: eq.id, maintenanceType: 'PERIODIC', status: { in: ['SCHEDULED', 'DUE'] } },
      })
      if (!existingKm) {
        await db.maintenanceSchedule.create({
          data: {
            equipmentId: eq.id, equipmentCode: eq.code, equipmentName: eq.name,
            maintenanceType: 'PERIODIC',
            title: `Servis na ${eq.maintenanceIntervalKm}km`,
            description: 'Periodično održavanje po kilometraži',
            triggerKm: nextKmService,
            triggerIntervalKm: eq.maintenanceIntervalKm,
            status: eq.totalKm >= nextKmService ? 'DUE' : 'SCHEDULED',
            priority: 'MEDIUM', autoGenerated: true,
          },
        })
        generated++
      }

      // 3. Time-based (godišnji pregled)
      if (eq.nextInspectionDate) {
        const existingAnnual = await db.maintenanceSchedule.findFirst({
          where: { equipmentId: eq.id, maintenanceType: 'ANNUAL', status: { in: ['SCHEDULED', 'DUE'] } },
        })
        if (!existingAnnual) {
          const daysUntil = Math.floor((new Date(eq.nextInspectionDate).getTime() - Date.now()) / (1000 * 60 * 60 * 24))
          await db.maintenanceSchedule.create({
            data: {
              equipmentId: eq.id, equipmentCode: eq.code, equipmentName: eq.name,
              maintenanceType: 'ANNUAL',
              title: 'Godišnji tehnički pregled',
              description: 'Kompletna godišnja inspekcija',
              triggerDate: eq.nextInspectionDate,
              triggerIntervalMonths: eq.inspectionIntervalMonths ?? 12,
              status: daysUntil < 0 ? 'OVERDUE' : daysUntil <= 30 ? 'DUE' : 'SCHEDULED',
              priority: daysUntil <= 30 ? 'HIGH' : 'MEDIUM',
              autoGenerated: true,
            },
          })
          generated++
        }
      }
    }

    revalidatePath('/dashboard')
    return { ok: true, generated }
  }

  // Supabase
  const supabase = await createSupabaseClient()
  const { data: equipment } = await supabase.from('equipment').select('*')
  let generated = 0

  for (const eq of equipment ?? []) {
    const nextHourService = (eq.last_maintenance_hours ?? 0) + (eq.maintenance_interval_hours ?? 500)
    const { data: existingHour } = await supabase.from('maintenance_schedule').select('id')
      .eq('equipment_id', eq.id).eq('maintenance_type', 'PREVENTIVE').in('status', ['SCHEDULED', 'DUE']).limit(1)

    if (!existingHour || existingHour.length === 0) {
      await supabase.from('maintenance_schedule').insert({
        equipment_id: eq.id, equipment_code: eq.code, equipment_name: eq.name,
        maintenance_type: 'PREVENTIVE', title: `Servis na ${eq.maintenance_interval_hours}h`,
        description: 'Preventivno održavanje po radnim satima',
        trigger_hours: nextHourService, trigger_interval: eq.maintenance_interval_hours,
        status: (eq.total_operating_hours ?? 0) >= nextHourService ? 'DUE' : 'SCHEDULED',
        priority: 'MEDIUM', auto_generated: true,
      })
      generated++
    }

    const nextKmService = (eq.last_maintenance_km ?? 0) + (eq.maintenance_interval_km ?? 10000)
    const { data: existingKm } = await supabase.from('maintenance_schedule').select('id')
      .eq('equipment_id', eq.id).eq('maintenance_type', 'PERIODIC').in('status', ['SCHEDULED', 'DUE']).limit(1)

    if (!existingKm || existingKm.length === 0) {
      await supabase.from('maintenance_schedule').insert({
        equipment_id: eq.id, equipment_code: eq.code, equipment_name: eq.name,
        maintenance_type: 'PERIODIC', title: `Servis na ${eq.maintenance_interval_km}km`,
        description: 'Periodično održavanje po kilometraži',
        trigger_km: nextKmService, trigger_interval_km: eq.maintenance_interval_km,
        status: (eq.total_km ?? 0) >= nextKmService ? 'DUE' : 'SCHEDULED',
        priority: 'MEDIUM', auto_generated: true,
      })
      generated++
    }

    if (eq.next_inspection_date) {
      const { data: existingAnnual } = await supabase.from('maintenance_schedule').select('id')
        .eq('equipment_id', eq.id).eq('maintenance_type', 'ANNUAL').in('status', ['SCHEDULED', 'DUE']).limit(1)

      if (!existingAnnual || existingAnnual.length === 0) {
        const daysUntil = Math.floor((new Date(eq.next_inspection_date).getTime() - Date.now()) / (1000 * 60 * 60 * 24))
        await supabase.from('maintenance_schedule').insert({
          equipment_id: eq.id, equipment_code: eq.code, equipment_name: eq.name,
          maintenance_type: 'ANNUAL', title: 'Godišnji tehnički pregled',
          description: 'Kompletna godišnja inspekcija',
          trigger_date: eq.next_inspection_date,
          trigger_interval_months: eq.inspection_interval_months ?? 12,
          status: daysUntil < 0 ? 'OVERDUE' : daysUntil <= 30 ? 'DUE' : 'SCHEDULED',
          priority: daysUntil <= 30 ? 'HIGH' : 'MEDIUM', auto_generated: true,
        })
        generated++
      }
    }
  }

  revalidatePath('/dashboard')
  return { ok: true, generated }
}

