import { NextRequest, NextResponse } from 'next/server'
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib'
import { getCurrentUser } from '@/lib/auth-server'
import { isDemoMode } from '@/lib/auth-mode'
import { db } from '@/lib/db'
import { createClientAsync as createSupabaseClient } from '@/lib/supabase/server'
import { transliterate } from '@/lib/pdf-utils'

export async function GET(request: NextRequest) {
  const user = await getCurrentUser()
  if (!user) return new NextResponse('Unauthorized', { status: 401 })

  let schedule: any[] = []
  if (isDemoMode()) {
    schedule = await db.maintenanceSchedule.findMany({ orderBy: [{ status: 'asc' }, { priority: 'asc' }] })
  } else {
    const supabase = await createSupabaseClient()
    const { data } = await supabase.from('maintenance_schedule').select('*').order('status', { ascending: true }).order('priority', { ascending: true })
    schedule = (data ?? []).map((s: any) => ({ equipmentCode: s.equipment_code, equipmentName: s.equipment_name, maintenanceType: s.maintenance_type, title: s.title, triggerHours: s.trigger_hours, triggerKm: s.trigger_km, triggerDate: s.trigger_date ? new Date(s.trigger_date) : null, status: s.status, priority: s.priority, autoGenerated: s.auto_generated, completionNotes: s.completion_notes, completedBy: s.completed_by }))
  }

  const pdfDoc = await PDFDocument.create()
  const font = await pdfDoc.embedFont(StandardFonts.Helvetica)
  const fontBold = await pdfDoc.embedFont(StandardFonts.HelveticaBold)
  const pageWidth = 595.28, pageHeight = 841.89, margin = 50
  let page = pdfDoc.addPage([pageWidth, pageHeight])
  let y = pageHeight - margin

  const addText = (text: string, x: number, yVal: number, opts: any = {}) => {
    const { size = 10, font: f = font, color = rgb(0, 0, 0) } = opts
    try { page.drawText(transliterate(text), { x, y: yVal, size, font: f, color }) } catch {}
  }

  addText('GSE CONTROL — SERVISNI PLANER', margin, y, { size: 16, font: fontBold }); y -= 20
  addText('ADR.OPS.C.007(b) — Maintenance Schedule', margin, y, { size: 10 }); y -= 15
  addText(`Generisao: ${user.full_name} (${user.role})`, margin, y, { size: 10 }); y -= 25

  const due = schedule.filter(s => s.status === 'DUE' || s.status === 'OVERDUE').length
  const completed = schedule.filter(s => s.status === 'COMPLETED').length
  addText(`Ukupno: ${schedule.length} | Na naplatu: ${due} | Zavrseno: ${completed}`, margin, y, { size: 11, font: fontBold }); y -= 20

  const cols = [margin, margin + 80, margin + 200, margin + 320, margin + 420]
  ;['Kod', 'Naziv', 'Trigger', 'Status', 'Prioritet'].forEach((h, i) => addText(h, cols[i], y, { size: 9, font: fontBold }))
  y -= 5; page.drawLine({ start: { x: margin, y }, end: { x: pageWidth - margin, y }, thickness: 0.5, color: rgb(0, 0, 0) }); y -= 11

  for (const s of schedule) {
    if (y < 80) { page = pdfDoc.addPage([pageWidth, pageHeight]); y = pageHeight - margin }
    addText(s.equipmentCode || '', cols[0], y, { size: 8 })
    addText((s.title || '').slice(0, 25), cols[1], y, { size: 8 })
    const trigger = [s.triggerHours ? `${s.triggerHours}h` : '', s.triggerKm ? `${s.triggerKm}km` : '', s.triggerDate ? new Date(s.triggerDate).toLocaleDateString('hr-HR') : ''].filter(Boolean).join(' ')
    addText(trigger || '-', cols[2], y, { size: 8 })
    addText(s.status, cols[3], y, { size: 8, color: s.status === 'OVERDUE' ? rgb(0.86, 0.15, 0.15) : s.status === 'DUE' ? rgb(0.79, 0.54, 0.04) : rgb(0, 0, 0) })
    addText(s.priority, cols[4], y, { size: 8 })
    y -= 10
  }

  addText(`GSE Control · ADR.OPS.C.007(b) · ${new Date().toLocaleString('hr-HR').slice(0, 16)}`, margin, 30, { size: 8, color: rgb(0.6, 0.6, 0.6) })

  const pdf = await pdfDoc.save()
  return new NextResponse(Buffer.from(pdf) as unknown as BodyInit, { headers: { 'Content-Type': 'application/pdf', 'Content-Disposition': `attachment; filename="maintenance-schedule-${new Date().toISOString().slice(0, 10)}.pdf"` } })
}
